/**
 * Helper to retrieve a localized string by key path
 * Supports fallback to English and parametric interpolation e.g. {name}
 */
export function getTranslation(lang, keyPath, fallback = '', params = {}) {
    const activeDict = translations[lang] || translations.en;
    const defaultDict = translations.en;

    const keys = keyPath.split('.');
    
    let value = activeDict;
    for (const k of keys) {
        if (value && typeof value === 'object' && k in value) {
            value = value[k];
        } else {
            value = null;
            break;
        }
    }

    // Fallback to English if not found in active language
    if (!value && activeDict !== defaultDict) {
        let fallbackVal = defaultDict;
        for (const k of keys) {
            if (fallbackVal && typeof fallbackVal === 'object' && k in fallbackVal) {
                fallbackVal = fallbackVal[k];
            } else {
                fallbackVal = null;
                break;
            }
        }
        value = fallbackVal;
    }

    if (!value) {
        value = fallback || keyPath;
    }

    if (typeof value === 'string' && params && Object.keys(params).length > 0) {
        return value.replace(/\{(\w+)\}/g, (_, match) => {
            return params[match] !== undefined ? params[match] : `{${match}}`;
        });
    }

    return value;
}
